def seed(db: Session) -> None:
    if db.query(University).count() == 0:
        for name, short, lat, lon, is_college in UNIVERSITIES:
            db.add(University(name=name, short_name=short, lat=lat, lon=lon,
                              is_college=is_college))
        db.commit()

    if not DEV_MODE or db.query(Listing).count() > 0:
        return

    unis = db.query(University).order_by(University.id).all()
    users = []
    for du in DEMO_USERS:
        uni = unis[du["uni"]]
        user = User(
            tg_id=du["tg_id"], username=du["username"], first_name=du["first_name"],
            university_id=uni.id, is_verified=du["verified"],
            lat=uni.lat, lon=uni.lon,
        )
        db.add(user)
        users.append(user)
    db.flush()

    for i, dl in enumerate(DEMO_LISTINGS):
        uni = unis[dl["uni"]]
        owner = users[i % len(users)]
        db.add(Listing(
            user_id=owner.id, kind=dl["kind"], title=dl["title"],
            description=dl.get("description", ""), category=dl["category"],
            subcategory=dl.get("subcategory"), deal_type=dl["deal_type"],
            format=dl.get("format", "offline"), price=dl.get("price"),
            exchange_for=dl.get("exchange_for"),
            lat=uni.lat + (i % 5 - 2) * 0.002, lon=uni.lon + (i % 3 - 1) * 0.003,
            university_id=uni.id, views=(i * 7) % 40,
        ))
    db.commit()
    print("[StudentSwap] Демо-данные загружены (DEV_MODE)")
